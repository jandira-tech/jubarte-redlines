//! M348 — long multi-table × short table free-mesh (eigenpal×employee_directory).

use std::io::Read;
use std::path::PathBuf;

use jubarte::comparer::WmlComparerSettings;
use jubarte::document_comparer::compare_documents_with_settings;

fn body_para_seq(xml: &str) -> String {
    let mut out = String::new();
    let mut rest = xml;
    if let Some(i) = rest.find("<w:body") {
        rest = &rest[i..];
    }
    if let Some(i) = rest.find("</w:body>") {
        rest = &rest[..i];
    }
    while let Some(start) = rest.find("<w:p") {
        let after = &rest[start..];
        let end_rel = after
            .find("</w:p>")
            .map(|j| j + "</w:p>".len())
            .or_else(|| after.find("/>").map(|j| j + 2));
        let Some(end_rel) = end_rel else { break };
        let p = &after[..end_rel];
        rest = &after[end_rel..];
        let has_ins = p.contains("<w:ins");
        let has_del = p.contains("<w:del");
        out.push(match (has_ins, has_del) {
            (true, true) => 'M',
            (true, false) => 'I',
            (false, true) => 'D',
            (false, false) => 'E',
        });
    }
    out
}

#[test]
fn eigenpal_x_employee_directory_has_mix() {
    let root = PathBuf::from(env!("CARGO_MANIFEST_DIR"));
    let a = root.join("../neurotic_docx_bench/corpus/word_based/docx_source/eigenpal_docx_editor_suggesting_mixed_edits.docx");
    let b = root.join(
        "../neurotic_docx_bench/corpus/word_based/docx_source/employee_directory_table_2.docx",
    );
    if !a.exists() || !b.exists() {
        eprintln!("skip: fixtures missing");
        return;
    }
    let out = compare_documents_with_settings(
        &std::fs::read(&a).unwrap(),
        &std::fs::read(&b).unwrap(),
        &WmlComparerSettings {
            author_for_revisions: "Redline".into(),
            merge_replaced_paragraphs: true,
            ..WmlComparerSettings::default()
        },
    )
    .expect("compare");
    let mut zip = zip::ZipArchive::new(std::io::Cursor::new(out)).unwrap();
    let mut f = zip.by_name("word/document.xml").unwrap();
    let mut xml = String::new();
    f.read_to_string(&mut xml).unwrap();
    let seq = body_para_seq(&xml);
    let mix = seq.chars().filter(|&c| c == 'M').count();
    assert!(
        mix >= 1,
        "Word free-meshes table headers (MIX≥2); got MIX={mix} seq={}",
        &seq[..seq.len().min(80)]
    );
}
