# Write every flag of the `jubarte` command line to docs/flags_datetime.md,
# from clap's own model (`examples/cli_flags.rs`): hidden tasks and flags,
# aliases, defaults, possible values, conflicts, the flags by long name and
# by short letter across tasks, the timestamp flags and the retired
# spellings. The Python and npm CLIs parse through the same clap model
# (`jubarte::cli::parse_json`), so the catalogue covers them too; what they
# refuse at run time is not listed here.
#
# The output depends only on the source (no date, no commit), so a change
# to any flag shows up as a diff:
#
#   scripts/cli_flags.sh           # rewrite docs/flags_datetime.md
#   scripts/cli_flags.sh --check   # exit 1 when the committed file drifted

set -euo pipefail
cd "$(dirname "$0")/.."
command -v cargo >/dev/null || export PATH="$HOME/.cargo/bin:$PATH"

target=docs/flags_datetime.md
render() {
  # REUSE-IgnoreStart (the header written into the generated file, not this script's)
  printf '%s\n' '<!--' \
    'SPDX-FileCopyrightText: 2026 Jandira Technologies, LLC' '' \
    'SPDX-License-Identifier: AGPL-3.0-only' '-->' ''
  # REUSE-IgnoreEnd
  printf '# jubarte CLI flags\n\n'
  printf 'Generated by `scripts/cli_flags.sh` from clap'"'"'s model (`examples/cli_flags.rs`); do not edit by hand. `scripts/cli_flags.sh --check` fails when this file no longer matches the source.\n\n'
  cargo run --quiet --example cli_flags
}

case "${1:-}" in
  --check)
    fresh=$(mktemp)
    trap 'rm -f "$fresh"' EXIT
    render > "$fresh"
    if ! diff -u "$target" "$fresh"; then
      echo "$target drifted from the CLI: run scripts/cli_flags.sh" >&2
      exit 1
    fi
    ;;
  "")
    render > "$target"
    echo "wrote $target" >&2
    ;;
  *)
    echo "usage: scripts/cli_flags.sh [--check]" >&2
    exit 2
    ;;
esac
