"""Point the checkout at the repository's new GitHub name.

    python3 scripts/repo_move.py            # dry run: what --apply would change
    python3 scripts/repo_move.py --apply    # rewrite the live files
    python3 scripts/repo_move.py --check    # fail while a live file names the old repository

The repository moves from jandira-tech/jubarte-redlines to
jandira-tech/jubarte (docs/REPO_MOVE.md is the runbook). GitHub redirects
the old URLs after a rename, but registry metadata, trusted publishers,
`gh -R` calls and the self-updater should name the real repository, so
every live file is rewritten in one commit made right after the rename.

Only the repository's name changes. The crate, PyPI and npm packages named
`jubarte-redlines` keep their names: the rewrite matches the qualified
`jandira-tech/jubarte-redlines` and three exact unqualified forms (the
self-updater's `REPO_NAME` and release.sh's "repository jubarte-redlines,"
trusted-publisher lines), never a bare `jubarte-redlines`.

Historical records are frozen (FROZEN): plans, handoffs, reviews, evidence
JSON and reports describe what was true when they were written, and their
links keep working through GitHub's redirect. The generated READMEs are
not rewritten here either: `scripts/library_readmes.py` regenerates them
from the rewritten sources, which also refreshes their source stamps.
"""

from __future__ import annotations

import argparse
import subprocess
import sys
from pathlib import Path

OLD = "jandira-tech/jubarte-redlines"
NEW = "jandira-tech/jubarte"

# Exact unqualified spellings of the repository name, and what each becomes.
NAMED = (
    ('const REPO_NAME: &str = "jubarte-redlines";', 'const REPO_NAME: &str = "jubarte";'),
    ("repository jubarte-redlines,", "repository jubarte,"),
)

# Paths kept as written: history, evidence and reports. A prefix ending in
# "/" freezes a directory.
FROZEN = (
    "docs/superpowers/",
    "docs/design/",
    "docs/refactoring_best_practices/",
    "docs/PR-1278-CI-ROUNDTRIP-REPORT.md",
    "docs/ZIP9_OXML_OPC_MIGRATION.md",
    "docs/OPENSSF_VERIFICATION.md",
    "docs/REPO_MOVE.md",
    "scripts/repo_move.py",
    "scripts/test_repo_move.py",
)

# Written by scripts/library_readmes.py; regenerated, never edited.
GENERATED_NAME = "README.md"
GENERATED_STAMP = "Generated by scripts/library_readmes.py"


def tracked(root: Path) -> list[str]:
    """Every file git tracks under `root`, as repository-relative paths."""
    out = subprocess.run(["git", "ls-files", "-z"], cwd=root, check=True, capture_output=True).stdout
    return [p for p in out.decode("utf-8").split("\0") if p]


def frozen(path: str) -> bool:
    return any(path == f or (f.endswith("/") and path.startswith(f)) for f in FROZEN)


def rewrite(text: str) -> str:
    """`text` with every live spelling of the old repository replaced."""
    for old, new in NAMED:
        text = text.replace(old, new)
    return text.replace(OLD, NEW)


def generated(text: str) -> bool:
    return GENERATED_STAMP in text[:2048]


def plan(root: Path) -> tuple[dict[str, str], list[str]]:
    """The files --apply rewrites (path to new text), and the generated ones
    that still name the old repository and need regenerating."""
    changes: dict[str, str] = {}
    regenerate: list[str] = []
    for path in tracked(root):
        if frozen(path):
            continue
        try:
            text = (root / path).read_text(encoding="utf-8")
        except (UnicodeDecodeError, FileNotFoundError, IsADirectoryError):
            continue
        new = rewrite(text)
        if new == text:
            continue
        if generated(text):
            regenerate.append(path)
        else:
            changes[path] = new
    return changes, regenerate


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--apply", action="store_true", help="rewrite the live files")
    mode.add_argument("--check", action="store_true", help="fail while a live file names the old repository")
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parent.parent)
    args = parser.parse_args(argv)

    changes, regenerate = plan(args.root)
    if args.check:
        stale = sorted([*changes, *regenerate])
        for path in stale:
            print(f"error: {path} still names {OLD}", file=sys.stderr)
        return 1 if stale else 0

    for path, new in sorted(changes.items()):
        old = (args.root / path).read_text(encoding="utf-8")
        hits = old.count(OLD) + sum(old.count(o) for o, _ in NAMED)
        print(f"{'rewrote' if args.apply else 'would rewrite'} {path} ({hits})")
        if args.apply:
            (args.root / path).write_text(new, encoding="utf-8")
    for path in sorted(regenerate):
        print(f"regenerate {path} (python3 scripts/library_readmes.py)")
    if not args.apply:
        print(f"dry run: {len(changes)} files to rewrite, {len(regenerate)} to regenerate; rerun with --apply")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
