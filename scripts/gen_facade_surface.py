"""Generate tests/facade_surface.rs from the committed API listing (A7).

    scripts/gen_facade_surface.py [LISTING] [OUT]
    # LISTING defaults to docs/refactoring_best_practices/api-baseline.txt
    # OUT defaults to tests/facade_surface.rs

The generated file holds one `use jubarte::<path> as _;` per publicly
nameable item of the listing: modules, structs, enums, unions, traits,
module-level functions, constants, statics, type aliases, macros and
re-exports (`use` lines). Impl blocks, fields, variants and associated
items are not nameable by a `use` and stay out. A function whose last
path segment owner is a type (`Owner::method`, second-to-last segment
uppercase) is a method, not a module-level fn, and stays out too.

Compiling the file is the gate (plan T4.0 AC3): a public path that
disappears from the facade breaks the build, cargo-semver-checks or not.
Regenerate after a deliberate API change, never edit by hand.
"""

from __future__ import annotations

import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_LISTING = ROOT / "docs/refactoring_best_practices/api-baseline.txt"
DEFAULT_OUT = ROOT / "tests/facade_surface.rs"

# Listing kinds a `use` statement can name.
NAMEABLE = frozenset({
    "module", "struct", "enum", "union", "trait", "function",
    "constant", "static", "type_alias", "macro", "use",
})

def _is_associated(path: str) -> bool:
    """`Owner::name` (or `module::Owner::name`): any path segment between
    `jubarte` and the item itself names a type, not a module."""
    segments = path.split("::")
    return any(seg[:1].isupper() for seg in segments[1:-1])

HEADER = """\
// SPDX-FileCopyrightText: 2026 Jandira Technologies, LLC
//
// SPDX-License-Identifier: AGPL-3.0-only

//! The facade surface gate (plan T4.0): one `use` per publicly nameable
//! item of the committed API listing.
//!
//! GENERATED by `scripts/gen_facade_surface.py` from
//! docs/refactoring_best_practices/api-baseline.txt - never edit by hand;
//! regenerate after a deliberate API change. The file compiling at all is
//! the assertion: a `jubarte::` path that disappeared fails this build.
//!
//! Every import is a nameless existence probe (`use … as _`), never a
//! binding, so rustc's unused-import lint has nothing real to say here -
//! the same standing exemption tests/common/mod.rs carries for dead_code.

#![allow(unused_imports)]
"""


def _item_path(kind: str, rest: str) -> str:
    """The listing's last column trimmed of its kind-specific detail."""
    if kind == "function":
        return rest.split(None, 1)[0] if rest else rest
    if ": " in rest:
        return rest.split(": ", 1)[0]
    if " = " in rest:
        return rest.split(" = ", 1)[0]
    return rest


def facade_uses(listing: str) -> list[str]:
    # A listing line carries surface `api` when the ITEM is public and
    # reachable, which includes items under private modules that a public
    # re-export names elsewhere (comment_settlement::KeptComment is listed
    # api because edit::KeptComment re-exports it). Such a path is not
    # nameable itself: every ancestor module must be an api module too.
    lines = [line.split("\t") for line in listing.splitlines() if "\t" in line]
    api_modules = {
        _item_path(f[1], f[3])
        for f in lines
        if f[0] == "api" and f[1] == "module"
    }
    uses: list[str] = []
    for fields in lines:
        if fields[0] != "api":
            continue
        kind, path = fields[1], _item_path(fields[1], fields[3])
        if kind not in NAMEABLE:
            continue
        if _is_associated(path):
            continue  # an inherent or trait method: not `use`-able
        if path.endswith("::*") or path.endswith("::_"):
            continue  # a glob re-export names its children, not itself
        segments = path.split("::")
        prefixes = [
            "::".join(segments[:i]) for i in range(2, len(segments))
        ]
        if any(prefix not in api_modules for prefix in prefixes):
            continue  # a private module in the chain: the re-export covers it
        uses.append(f"use {path} as _;")
    return sorted(set(uses))


def main(argv: list[str]) -> int:
    listing_path = Path(argv[0]) if argv else DEFAULT_LISTING
    out_path = Path(argv[1]) if len(argv) > 1 else DEFAULT_OUT
    uses = facade_uses(listing_path.read_text())
    if not uses:
        print(f"no api items found in {listing_path}", file=sys.stderr)
        return 1
    plain = [
        u for u in uses
        if not u.startswith("use jubarte::cli::")
        and u != "use jubarte::cli as _;"
        and not u.startswith("use jubarte::edit::inline")
        and not u.startswith("use jubarte::update")
    ]
    cli_uses = [u for u in uses if u not in plain]
    update_uses = [u for u in uses if u.startswith("use jubarte::update")]
    cli_uses = [u for u in cli_uses if u not in update_uses]
    gated = ""
    if cli_uses:
        gated += (
            "#[cfg(feature = \"cli\")]\nmod cli_gated {\n"
            + "".join(f"    {u}\n" for u in cli_uses)
            + "}\n"
        )
    if update_uses:
        gated += (
            "#[cfg(feature = \"self-update\")]\nmod update_gated {\n"
            + "".join(f"    {u}\n" for u in update_uses)
            + "}\n"
        )
    body = (
        HEADER + "\n".join(plain) + "\n" + gated
        + "\n#[test]\nfn facade_surface_resolves() {}\n"
    )
    out_path.write_text(body)
    # rustfmt's import order (a version sort, not plain ASCII) is the one
    # `cargo fmt --check` enforces on the committed file.
    subprocess.run(
        ["rustfmt", "--edition", "2024", str(out_path)], check=True,
    )
    print(f"{out_path}: {len(uses)} use statements")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
